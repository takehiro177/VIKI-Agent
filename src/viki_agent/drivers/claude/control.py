"""The claude.exe argv (the only place CLI flags are chosen) and the control glue.

The glue hands the control protocol to the SDK's Query through the public ClaudeSDKClient,
fed by ClaudeTransport, which only ever passes it control frames. This stays free of
`claude_agent_sdk._internal` (ruff TID251) and small; otherwise hand-roll the protocol.
"""

from __future__ import annotations

import asyncio
import base64
from collections.abc import AsyncIterator, Awaitable, Callable, Sequence
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any
from uuid import UUID

from claude_agent_sdk import CanUseTool, ClaudeAgentOptions, ClaudeSDKClient

from viki_agent.drivers.claude.transport import ClaudeTransport
from viki_agent.turn_input import (
    Attachment,
    AttachmentUnavailable,
    TurnInput,
    TurnInputError,
    coerce,
)

# Modes VIKI may start a session in or switch to. Never bypassPermissions or dontAsk.
# CLI 2.1.259 lists "manual" where older builds said "default"; scripts/capture.py records
# which it accepts.
PERMISSION_MODES = frozenset({"default", "manual", "acceptEdits", "auto", "plan"})
EFFORTS = frozenset({"low", "medium", "high", "xhigh", "max"})
# Mirrors settings.MAX_CHAT_WORKSPACES; this module can't import settings.py (settings.py
# already imports PERMISSION_MODES/EFFORTS from here, so the reverse import would cycle).
MAX_ADD_DIRS = 7
CONTROL_TIMEOUT_S = 5.0
# An enable or a reconnect replies only once the server has connected or failed to. This bounds
# both MCP calls, under the SDK's own 60 s, and is read at each call.
MCP_TOGGLE_TIMEOUT_S = 45.0


@dataclass(frozen=True)
class Launch:
    """Which transcript a claude process writes to.

    new: `Launch(id)` · resume: `Launch(id, resume=True)` · fork: `Launch(new_id, fork_of=old_id)`.
    Ids are always generated by the app (client UUIDs), never by the CLI.
    `mcp_config` is the absolute path of the app's resolved MCP config file for this spawn, or
    None (no `--mcp-config` element).
    `cwd` is the folder this spawn runs in; None means `DriverConfig.vault`. `build_argv` does
    not read it.
    `read_only_tools` asks for the read-only file tools only: `build_argv` adds
    `--tools=Read,Glob,Grep` and `--strict-mcp-config`, and refuses an `mcp_config` beside it.
    Only the inbox suggestion run sets it (hard rule 4's third exception).
    `add_dirs` is up to MAX_ADD_DIRS absolute paths, the user's ticked `chat.workspace_ids`
    resolved by the caller: `build_argv` turns each into its own `--add-dir=<path>` element and
    refuses more than MAX_ADD_DIRS, a non-absolute entry, or either beside `mcp_config` or
    `read_only_tools` (hard rule 4's fourth exception, ADR-050).
    `bot_memory_settings` is the private, generated settings file for a Bot's native auto-memory
    directory and the vault instruction files it skips. It is resolved again before each spawn,
    including resume.
    `code_worktree` is that Bot session's resolved private code copy. Its single `--add-dir`
    needs Bot memory settings, permits app MCP, and excludes ordinary `add_dirs` and `cwd`.
    `append_system_prompt` is that Bot session's instructions, memory rule and Bot rules, resolved
    again before each spawn. It is no flag: the transport sends it in initialize (ADR-084), and it
    needs Bot memory settings. Kept out of repr: it is the user's own text.
    `agent_cli` asks for a VIKI Agent CLI key in this process's environment, which
    `SessionManager._claude_driver` issues; `build_argv` does not read it.
    Bot bindings, grants and filesystem admission are the caller's responsibility.
    """

    session_id: str
    resume: bool = False
    fork_of: str | None = None
    mcp_config: str | None = None
    cwd: Path | None = None
    read_only_tools: bool = False
    add_dirs: tuple[str, ...] = ()
    bot_memory_settings: str | None = None
    code_worktree: str | None = None
    append_system_prompt: str | None = field(default=None, repr=False)
    agent_cli: bool = False


def build_argv(
    cli: Sequence[str],
    launch: Launch,
    *,
    mode: str,
    effort: str,
    model: str | None = None,
) -> list[str]:
    """argv for one claude process. `cli` is the executable (plus a script, for test fakes).

    Deliberately absent: --bare, --setting-sources and --system-prompt, so the child loads the
    same CLAUDE.md, skills, hooks and system prompt as the user's terminal; only a Bot session's
    settings file names the vault's own instruction files for it to skip. A Bot session's
    `append_system_prompt` adds no element: the transport sends it in initialize.
    `--mcp-config=<absolute path>` is present only for a resolved app MCP config.
    `--settings=<absolute path>` names only a generated Bot memory settings file.
    `--tools=Read,Glob,Grep` and `--strict-mcp-config` are present only for `read_only_tools`.
    `--add-dir=<absolute path>` elements, one per `launch.add_dirs` entry, follow the
    session-id/resume/fork-session elements and precede `--mcp-config` (ADR-050).
    A Bot's `code_worktree` instead adds one element before its settings and optional app MCP.
    """
    if mode not in PERMISSION_MODES:
        raise ValueError(f"permission mode not allowed: {mode!r}")
    if effort not in EFFORTS:
        raise ValueError(f"unknown effort: {effort!r}")
    argv = [
        *cli,
        "-p",
        "--input-format", "stream-json",
        "--output-format", "stream-json",
        "--verbose",
        "--include-partial-messages",
        "--include-hook-events",
        "--thinking-display", "summarized",
        "--permission-prompt-tool", "stdio",
        "--permission-mode", mode,
        f"--effort={effort}",
    ]  # fmt: skip
    # Equals form throughout, so an id can never be parsed as a separate flag.
    if launch.fork_of:
        argv += [
            f"--resume={launch.fork_of}",
            "--fork-session",
            f"--session-id={launch.session_id}",
        ]
    elif launch.resume:
        argv.append(f"--resume={launch.session_id}")
    else:
        argv.append(f"--session-id={launch.session_id}")
    if launch.code_worktree is not None:
        path = Path(launch.code_worktree)
        try:
            canonical_id = str(UUID(path.name))
        except ValueError:
            canonical_id = ""
        # Lexical shape only; the resolver owns Bot, grant and filesystem authority.
        if (
            not path.is_absolute()
            or path.name != canonical_id
            or not path.parent.name.endswith("-worktrees")
            or ".." in path.parts
            or "\x00" in launch.code_worktree
            or launch.bot_memory_settings is None
            or launch.add_dirs
            or launch.read_only_tools
            or launch.fork_of is not None
            or launch.cwd is not None
        ):
            raise ValueError("invalid Bot code worktree")
        argv.append(f"--add-dir={launch.code_worktree}")
    if launch.add_dirs:
        # Hard rule 4's fourth exception (ADR-050): never beside a resolved MCP config or the
        # read-only inbox-suggestion launch.
        if launch.mcp_config is not None or launch.read_only_tools:
            raise ValueError("add dirs cannot be combined with an mcp config or read-only tools")
        if len(launch.add_dirs) > MAX_ADD_DIRS:
            raise ValueError("too many add dirs")
        for directory in launch.add_dirs:
            if not Path(directory).is_absolute():
                raise ValueError("add dir path must be absolute")
            argv.append(f"--add-dir={directory}")
    if launch.bot_memory_settings is not None:
        path = Path(launch.bot_memory_settings)
        if (
            not path.is_absolute()
            or path.parent.name != "bot-memory-settings"
            or path.suffix != ".json"
            or len(path.stem) != 64
            or any(c not in "0123456789abcdef" for c in path.stem)
            or launch.read_only_tools
            or launch.add_dirs
            or launch.fork_of is not None
        ):
            raise ValueError("invalid Bot memory settings")
        argv.append(f"--settings={path}")
    if launch.append_system_prompt is not None and launch.bot_memory_settings is None:
        raise ValueError("a system prompt is only for a Bot session")
    if launch.mcp_config is not None:
        # A relative path would resolve against the child's cwd (the vault), not the app's file.
        if not Path(launch.mcp_config).is_absolute():
            raise ValueError("mcp config path must be absolute")
        argv.append(f"--mcp-config={launch.mcp_config}")
    if launch.read_only_tools:
        # Hard rule 4's third exception. --strict-mcp-config
        # still loads the servers --mcp-config names, so a read-only launch names none.
        if launch.mcp_config is not None:
            raise ValueError("a read-only launch takes no mcp config")
        argv += ["--tools=Read,Glob,Grep", "--strict-mcp-config"]
    if model:
        argv.append(f"--model={model}")
    return argv


def login_argv(cli: Sequence[str]) -> list[str]:
    """argv for Claude Code's own sign-in, which the user starts from VIKI with a click
    (`provider_login`). `--claudeai` keeps it on the subscription route: no `--console`,
    `--sso` or `--email`."""
    return [*cli, "auth", "login", "--claudeai"]


async def _user_frame(
    content: str | list[dict[str, Any]], steer_id: str | None
) -> AsyncIterator[dict[str, Any]]:
    """The one user frame `ClaudeControl.send` hands the SDK's iterable input, which adds
    `session_id`. A steer's frame also carries `priority` "next", so the CLI folds it into the
    running turn after the current tool calls, and `uuid` (the steer id), which the CLI's
    command_lifecycle frames name as their `command_uuid`."""
    frame: dict[str, Any] = {"type": "user", "message": {"role": "user", "content": content}}
    if steer_id is not None:
        frame |= {"parent_tool_use_id": None, "priority": "next", "uuid": steer_id}
    yield frame


class ClaudeControl:
    """Control calls for one claude process. interrupt, set_model, set_permission_mode,
    context_usage, mcp_status and stop_task are bounded by `control_timeout_s`, and
    toggle_mcp_server and reconnect_mcp_server by `MCP_TOGGLE_TIMEOUT_S`; an unexpected
    exit fails pending calls at once (the transport raises ProcessError). start() is bounded by
    the SDK's initialize timeout (60 s: MCP servers may be slow), send() by the stdin pipe.

    A call that times out leaves one entry in Query's pending-request table (the asyncio
    cancellation bypasses its own cleanup); harmless, and the public API offers no better."""

    def __init__(
        self,
        transport: ClaudeTransport,
        can_use_tool: CanUseTool,
        *,
        control_timeout_s: float = CONTROL_TIMEOUT_S,
    ) -> None:
        self._transport = transport
        self._timeout = control_timeout_s
        self._client = ClaudeSDKClient(
            ClaudeAgentOptions(can_use_tool=can_use_tool), transport=transport
        )

    async def start(self) -> dict[str, Any]:
        """Spawn claude and finish the initialize handshake. Returns the CLI's reply
        (commands, agents, models, account, pid, ...)."""
        await self._client.connect()
        return await self._client.get_server_info() or {}

    async def send(
        self,
        turn: str | TurnInput,
        session_id: str,
        resolve_attachment: Callable[[Attachment], Awaitable[bytes]] | None = None,
        *,
        steer_id: str | None = None,
    ) -> None:
        """Use the public SDK iterable-input branch for text plus image content blocks, and for
        a steer (`steer_id`), whose one user frame `_user_frame` builds."""
        try:
            value = coerce(turn)
        except TurnInputError:
            raise ValueError("invalid turn") from None
        if not value.attachments:
            if steer_id is None:
                await self._client.query(value.text, session_id=session_id)
            else:
                await self._client.query(_user_frame(value.text, steer_id), session_id=session_id)
            return
        if resolve_attachment is None:
            raise AttachmentUnavailable

        # Every block is built before query(), so a refusal here has written nothing to the CLI.
        content: list[dict[str, Any]] = []
        if value.text:
            content.append({"type": "text", "text": value.text})
        for attachment in value.attachments:
            try:
                data = await resolve_attachment(attachment)
            except Exception as exc:  # never CancelledError: a shutdown stays a cancellation
                transient = getattr(exc, "code", None) == "busy"
                raise AttachmentUnavailable(transient=transient) from None
            if not isinstance(data, bytes) or len(data) != attachment.byte_size:
                raise AttachmentUnavailable
            encoded = await asyncio.to_thread(
                lambda data=data: base64.b64encode(data).decode("ascii")
            )
            content.append(
                {
                    "type": "image",
                    "source": {
                        "type": "base64",
                        "media_type": attachment.media_type,
                        "data": encoded,
                    },
                }
            )
        await self._client.query(_user_frame(content, steer_id), session_id=session_id)

    async def interrupt(self) -> None:
        await self._bounded(self._client.interrupt())

    async def set_model(self, model: str | None) -> None:
        await self._bounded(self._client.set_model(model))

    async def set_permission_mode(self, mode: str) -> None:
        if mode not in PERMISSION_MODES:
            raise ValueError(f"permission mode not allowed: {mode!r}")
        await self._bounded(self._client.set_permission_mode(mode))  # type: ignore[arg-type]

    async def context_usage(self) -> dict[str, Any]:
        return dict(await self._bounded(self._client.get_context_usage()))

    async def mcp_status(self) -> dict[str, Any]:
        return dict(await self._bounded(self._client.get_mcp_status()))

    async def toggle_mcp_server(self, name: str, enabled: bool) -> None:
        async with asyncio.timeout(MCP_TOGGLE_TIMEOUT_S):
            await self._client.toggle_mcp_server(name, enabled)

    async def reconnect_mcp_server(self, name: str) -> None:
        async with asyncio.timeout(MCP_TOGGLE_TIMEOUT_S):
            await self._client.reconnect_mcp_server(name)

    async def stop_task(self, task_id: str) -> None:
        await self._bounded(self._client.stop_task(task_id))

    async def close(self) -> None:
        """Let claude finish and exit (its last frames still reach the sink), then tear down the
        SDK side. Even a cancelled close leaves no process behind."""
        try:
            await self._transport.shutdown()
            await self._client.disconnect()
        finally:
            self._transport.abort()

    async def _bounded[T](self, call: Awaitable[T]) -> T:
        async with asyncio.timeout(self._timeout):
            return await call
