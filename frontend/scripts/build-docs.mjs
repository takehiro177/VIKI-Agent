function outputFiles(directory) {
  if (!fs.existsSync(directory)) return [];
  const files = [];
  for (const item of fs.readdirSync(directory, { withFileTypes: true })) {
    const target = path.join(directory, item.name);
    if (item.isSymbolicLink()) throw new Error("Generated output cannot contain symbolic links");
    if (item.isDirectory()) files.push(...outputFiles(target));
    else files.push(target);
  }
  return files;
}

export function writeSite(site, { check = false } = {}) {
  safePath(site.root, site.output);
  const obsolete = outputFiles(site.output).filter((file) => !site.files.has(file));
  const stale = [...site.files].filter(
    ([file, content]) =>
      !fs.existsSync(file) || fs.readFileSync(safePath(site.root, file), "utf8") !== content,
  );
  if (check) {
    if (obsolete.length || stale.length)
      throw new Error(
        `HTML documentation is stale (${stale.length} changed, ${obsolete.length} obsolete); run npm run build:docs`,
      );
    return;
  }
  for (const file of obsolete) {
    safePath(site.root, file);
    if (!fs.readFileSync(file, "utf8").startsWith(marker))
      throw new Error("Refusing to remove an unrecognized generated file");
    fs.unlinkSync(file);
  }
  for (const [file, content] of stale) {
    safePath(site.root, under(site.output, file));
    if (fs.existsSync(file) && !fs.readFileSync(file, "utf8").startsWith(marker)) {
      throw new Error("Refusing to overwrite an unrecognized generated file");
    }
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content, "utf8");
  }
}

export function validateSite(site) {
  const queue = [path.join(site.root, "docs", "index.html")];
  const visited = new Set();
  let links = 0;
  function read(file) {
    safePath(site.root, file);
    return site.files.get(file) ?? fs.readFileSync(file, "utf8");
  }
  while (queue.length) {
    const file = queue.shift();
    if (visited.has(file)) continue;
    visited.add(file);
    const source = read(file);
    for (const match of source.matchAll(/(?:href|src|poster|action)\s*=\s*["']([^"']+)["']/gi)) {
      const value = match[1].replaceAll("&amp;", "&");
      if (/^(?:https?:|mailto:|data:)/i.test(value)) continue;
      const url = new URL(value, pathToFileURL(file));
      const target = safePath(site.root, fileURLToPath(url));
      const name = path.relative(site.root, target).split(path.sep).join("/");
      if (name.endsWith(".md")) throw new Error(`HTML navigation points to Markdown: ${name}`);
      if (
        !site.files.has(target) &&
        (!fs.existsSync(target) || fs.statSync(target).isDirectory())
      ) {
        throw new Error(`Missing HTML navigation or asset: ${name}`);
      }
      links++;
      if (!name.endsWith(".html")) continue;
      if (url.hash) {
        const id = decodeURIComponent(url.hash.slice(1));
        const ids = [...read(target).matchAll(/id=["']([^"']+)["']/g)].map((item) => item[1]);
        if (!ids.includes(id)) throw new Error(`Missing HTML fragment: ${name}#${id}`);
      }
      if (!name.startsWith("docs/assets/motion/")) queue.push(target);
    }
  }
  return { pages: visited.size, links };
}

